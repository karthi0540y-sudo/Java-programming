public class Relational {
    public static void main(String[] args) {
        int a, b;

        a = 10;
        b = 20;

        System.out.println(a > b);
        System.out.println(10 < 20);
        System.out.println(a < b);
        // System.out.println(10 = 20); // Invalid in Java
        System.out.println(a == b);
    }
}